#!/bin/bash
# Пересобрать и заново выдать разрешение.
#
# Подпись ad-hoc не имеет постоянной личности: TCC запоминает требование,
# включающее хеш бинаря, поэтому после каждой пересборки выданный
# Универсальный доступ перестаёт засчитываться — переключатель остаётся
# включённым, но относится к прежней сборке. Лечится сбросом записи и
# повторной выдачей.
#
# Чинится радикально самоподписанным сертификатом с постоянной личностью,
# но это отдельная возня; пока дешевле пересдавать разрешение одной командой.
set -uo pipefail
cd "$(dirname "$0")"

./bundle.sh   # он же остановит работающее приложение
tccutil reset Accessibility local.whisper.dictate
open Dictate.app
echo
echo "Выдай Универсальный доступ в открывшемся окне (или Настройки →"
echo "Конфиденциальность → Универсальный доступ → Dictate)."
echo "Приложение подхватит и напишет 'готов' в:"
echo "  ~/Library/Application Support/whisper-local/dictate.log"
